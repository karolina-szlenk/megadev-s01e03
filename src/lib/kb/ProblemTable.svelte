<script lang="ts">
  import reports from '#lib/data/reports-4471.json';
  import notes from '#lib/data/desk-notes.json';
  import { type Report } from '#lib/kb/causes';
  import { tenantOf } from '#lib/kb/locales';
  import { PROBLEM_TITLE, splitTicket, type Problem } from '#lib/kb/problems';

  // tickets: where each problem is tracked now, problem → issue URL.
  let { ticket, tickets = {} }: { ticket: number; tickets?: Partial<Record<Problem, string>> } = $props();

  const split = $derived(splitTicket(reports as Report[], ticket, tenantOf, notes.oneDayMove));
  const issueNo = (url: string) => url.split('/').pop();
</script>

<p class="sum">
  <strong>{split.merged}</strong> reports merged into #{ticket} ·
  <strong>{split.groups.length}</strong>
  {split.groups.length === 1 ? 'problem' : 'problems'}
</p>

<table>
  <thead>
    <tr><th>problem</th><th>reports</th><th>tenants</th><th>seen</th><th>ticket</th></tr>
  </thead>
  <tbody>
    {#each split.groups as g (g.problem)}
      <tr>
        <td><code>{g.problem}</code><br /><span class="what">{PROBLEM_TITLE[g.problem]}</span></td>
        <td>
          {g.reports.length}
          {#if g.footnote && 'oneDay' in g.footnote}<br /><span class="what">incl. {g.footnote.oneDay} one-day</span>{/if}
          {#if g.footnote && 'filedUnder' in g.footnote}<br /><span class="what">also counted in {g.footnote.filedUnder.join(', ')}</span>{/if}
        </td>
        <td>{g.tenants}</td>
        <td>{g.firstSeen} → {g.lastSeen}</td>
        <td>
          {#if tickets[g.problem]}<a href={tickets[g.problem]}>#{issueNo(tickets[g.problem]!)}</a>{:else}<span class="none">none yet</span>{/if}
        </td>
      </tr>
    {/each}
  </tbody>
</table>

<p class="what">Counted the desk's way: each report where its tenant and channel file it. One-day moves are counted there too, and have their own row.</p>

